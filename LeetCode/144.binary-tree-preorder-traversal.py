# @lc code=start
# Definition for a binary tree node.
# class TreeNode:
#     def __init__(self, val=0, left=None, right=None):
#         self.val = val
#         self.left = left
#         self.right = right
class Solution:
    def preorderTraversal(self, root: Optional[TreeNode]) -> List[int]:
        result = []

        def preorder(node):
            if not node:
                return
            # 访问当前节点
            result.append(node.val)
            # 递归遍历左子树
            preorder(node.left)
            # 递归遍历右子树
            preorder(node.right)

        preorder(root)
        return result
        
